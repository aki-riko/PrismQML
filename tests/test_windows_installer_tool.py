def test_generate_is_atomic_and_does_not_rewrite_identical_output(tmp_path):
    manifest_path = _write_manifest(tmp_path)
    manifest = load_manifest(manifest_path)
    output_path = tmp_path / "installer.generated.iss"

    first = generate_installer(manifest, output_path, "1.0.0")
    first_timestamp = output_path.stat().st_mtime_ns
    second = generate_installer(manifest, output_path, "1.0.0")

    assert first.changed is True
    assert second.changed is False
    assert first.sha256 == second.sha256
    assert output_path.stat().st_mtime_ns == first_timestamp
    assert check_installer(manifest, output_path, "1.0.0").sha256 == first.sha256


def test_generate_replaces_non_utf8_generated_output(tmp_path):
    manifest = load_manifest(_write_manifest(tmp_path))
    output_path = tmp_path / "installer.generated.iss"
    output_path.write_bytes(b"\xff\xfe stale")

    result = generate_installer(manifest, output_path, "1.0.0")

    assert result.changed is True
    assert output_path.read_text(encoding="utf-8").startswith(
        "; SPDX-License-Identifier: MIT"
    )


def test_check_reports_missing_and_stale_outputs(tmp_path):
    manifest = load_manifest(_write_manifest(tmp_path))
    output_path = tmp_path / "installer.generated.iss"

    with pytest.raises(ManifestError, match="missing") as missing:
        check_installer(manifest, output_path, "1.0.0")
    assert missing.value.exit_code == EXIT_STALE_OUTPUT

    output_path.write_text("stale\n", encoding="utf-8")
    with pytest.raises(ManifestError, match="stale") as stale:
        check_installer(manifest, output_path, "1.0.0")
    assert stale.value.exit_code == EXIT_STALE_OUTPUT


def test_json_cli_has_stable_generate_check_and_error_shapes(tmp_path, capsys):
    manifest_path = _write_manifest(tmp_path)
    output_path = tmp_path / "installer.generated.iss"
    common = [
        "--json",
        "--manifest",
        str(manifest_path),
        "--version",
        "1.0.0",
        "--output",
        str(output_path),
    ]

    assert main(["generate", *common]) == EXIT_OK
    generated = json.loads(capsys.readouterr().out)
    assert generated["ok"] is True
    assert generated["command"] == "generate"
    assert generated["changed"] is True
    assert generated["output"] == str(output_path.resolve())

    assert main(["check", *common]) == EXIT_OK
    checked = json.loads(capsys.readouterr().out)
    assert checked["ok"] is True
    assert checked["command"] == "check"

    output_path.write_text("stale\n", encoding="utf-8")
    assert main(["check", *common]) == EXIT_STALE_OUTPUT
    failed = json.loads(capsys.readouterr().out)
    assert failed == {
        "ok": False,
        "command": "check",
        "error": {
            "code": "stale_output",
            "message": f"generated installer is stale: {output_path.resolve()}",
        },
    }


