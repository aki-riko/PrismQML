def _manifest_data(**overrides):
    data = {
        "schema": 1,
        "app_id": "8F3A9C2E-5B1D-4E7A-9C6F-A1B2C3D4E5F6",
        "name": "ExampleApp",
        "publisher": "Aquila",
        "executable": "ExampleApp.exe",
        "aumid": "PrismQML.ExampleApp",
        "install_scope": "user",
        "dist_dir": "build/main.dist",
    }
    data.update(overrides)
    return data


def _write_manifest(tmp_path: Path, **overrides) -> Path:
    path = tmp_path / "prismqml-installer.json"
    path.write_text(
        json.dumps(_manifest_data(**overrides), ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return path


def test_minimal_manifest_renders_silent_next_launch_contract(tmp_path):
    manifest_path = _write_manifest(tmp_path)
    manifest = load_manifest(manifest_path)
    output_path = tmp_path / "installer.generated.iss"

    rendered = render_installer(manifest, output_path, "1.2.3.4")

    assert "; Generated by prismqml-installer. DO NOT EDIT." in rendered
    assert "AppId={{8F3A9C2E-5B1D-4E7A-9C6F-A1B2C3D4E5F6}" in rendered
    assert "AppVersion={#PrismAppVersion}" in rendered
    assert "DefaultDirName={localappdata}\\Programs\\{#PrismAppName}" in rendered
    assert "PrivilegesRequired=lowest" in rendered
    assert "CloseApplications=yes" in rendered
    assert "RestartApplications=no" in rendered
    assert "Flags: nowait postinstall skipifsilent" in rendered
    assert "/RESTARTAPPLICATIONS" not in rendered
    assert "/AUTORESTARTAPP" not in rendered
    assert str(tmp_path) not in rendered


def test_machine_manifest_and_optional_sections_are_rendered_relatively(tmp_path):
    (tmp_path / "installer").mkdir()
    manifest_path = _write_manifest(
        tmp_path,
        install_scope="machine",
        homepage="https://example.test/example-app",
        icon="assets/app.ico",
        extension_include="installer/legacy.issinc",
        installer_output_dir="release/setup",
        output_name="ExampleApp_Setup_{version}",
    )
    output_path = tmp_path / "generated" / "installer.iss"
    manifest = load_manifest(manifest_path)

    rendered = render_installer(manifest, output_path, "2.0.0")

    assert "DefaultDirName={autopf}\\{#PrismAppName}" in rendered
    assert "PrivilegesRequired=admin" in rendered
    assert '#define PrismAppURL "https://example.test/example-app"' in rendered
    assert '#define PrismSetupIcon "..\\assets\\app.ico"' in rendered
    assert '#define PrismDistDir "..\\build\\main.dist"' in rendered
    assert "OutputDir=..\\release\\setup" in rendered
    assert "OutputBaseFilename=ExampleApp_Setup_2.0.0" in rendered
    assert '#include "..\\installer\\legacy.issinc"' in rendered
    assert str(tmp_path) not in rendered


